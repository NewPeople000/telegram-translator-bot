def generate_quiz_session(lang_code: str, count: int = 5) -> List[dict]:
    """
    Generate a quiz session with multiple choice questions.
    Returns a list of dicts:
    [
        {
            "word": "water",
            "correct": "suv",
            "options": ["suv", "kitob", "oy", "vaqt"],
            "correct_idx": 0,
            "lang": "en",
            "lang_name": "🇬🇧 Ingliz tili"
        },
        ...
    ]
    """
    bank = WORD_BANKS.get(lang_code)
    if not bank:
        return []

    lang_info = QUIZ_LANGUAGES.get(lang_code, {"name": lang_code, "flag": "🌐"})
    lang_display = f"{lang_info['flag']} {lang_info['name']}"

    # Pick random distinct questions
    sample_size = min(count, len(bank))
    selected_pairs = random.sample(bank, sample_size)

    all_translations = list({trans for _, trans in bank})

    questions = []
    for word, correct_trans in selected_pairs:
        # Choose 3 distractors
        distractors = [t for t in all_translations if t != correct_trans]
        sample_distractors = random.sample(distractors, min(3, len(distractors)))
        
        options = sample_distractors + [correct_trans]
        random.shuffle(options)
        correct_idx = options.index(correct_trans)

        questions.append({
            "word": word,
            "correct": correct_trans,
            "options": options,
            "correct_idx": correct_idx,
            "lang": lang_code,
            "lang_name": lang_display,
            "vocab_id": None,
        })

    return questions
